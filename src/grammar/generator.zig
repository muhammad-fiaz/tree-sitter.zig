const std = @import("std");
const grammar_mod = @import("../grammar/root.zig");
const abi = @import("../language/abi.zig");

pub const Grammar = grammar_mod.Grammar;
pub const Rule = grammar_mod.Rule;
pub const RuleTag = grammar_mod.RuleTag;

pub const SymbolKind = enum {
    end,
    terminal,
    non_terminal,
};

pub const SymbolInfo = struct {
    id: u16,
    name: []const u8,
    kind: SymbolKind,
    named: bool = true,
    visible: bool = true,
};

pub const Production = struct {
    lhs: u16,
    rhs: []const u16,
    dynamic_precedence: i16 = 0,
    production_id: u16 = 0,
};

pub const ActionKind = enum {
    shift,
    reduce,
    accept,
    recover,
};

pub const GeneratedAction = struct {
    kind: ActionKind,
    state: u16 = 0,
    symbol: u16 = 0,
    child_count: u8 = 0,
    dynamic_precedence: i16 = 0,
    production_id: u16 = 0,
    extra: bool = false,
    reusable: bool = false,
};

pub const ActionGroup = struct {
    index: usize,
    count: u8,
    reusable: bool,
    actions: []GeneratedAction,
};

pub const GeneratedData = struct {
    allocator: std.mem.Allocator,
    language_name: []const u8 = "unknown",
    abi_version: u32 = 14,
    state_count: u32 = 0,
    large_state_count: u32 = 0,
    symbol_count: u32 = 0,
    alias_count: u32 = 0,
    token_count: u32 = 0,
    external_token_count: u32 = 0,
    field_count: u32 = 0,
    max_alias_sequence_length: u16 = 0,
    production_id_count: u32 = 0,

    symbol_names: [][]const u8 = &.{},
    symbol_map: []u16 = &.{},
    symbol_metadata: []abi.TSSymbolMetadata = &.{},
    field_names: []?[]const u8 = &.{},
    field_map_slices: []abi.TSMapSlice = &.{},
    field_map_entries: []abi.TSFieldMapEntry = &.{},
    alias_sequences: []u16 = &.{},
    primary_state_ids: []u16 = &.{},
    lex_modes: []abi.TSLexerMode = &.{},
    small_parse_table: []u16 = &.{},
    small_parse_table_map: []u32 = &.{},
    action_groups: []ActionGroup = &.{},

    pub fn init(allocator: std.mem.Allocator) GeneratedData {
        return .{ .allocator = allocator };
    }

    pub fn deinit(self: *GeneratedData) void {
        const gpa = self.allocator;
        gpa.free(self.language_name);
        for (self.symbol_names) |s| gpa.free(s);
        gpa.free(self.symbol_names);
        gpa.free(self.symbol_map);
        gpa.free(self.symbol_metadata);
        for (self.field_names) |maybe_f| {
            if (maybe_f) |f| gpa.free(f);
        }
        gpa.free(self.field_names);
        gpa.free(self.field_map_slices);
        gpa.free(self.field_map_entries);
        gpa.free(self.alias_sequences);
        gpa.free(self.primary_state_ids);
        gpa.free(self.lex_modes);
        gpa.free(self.small_parse_table);
        gpa.free(self.small_parse_table_map);
        for (self.action_groups) |ag| gpa.free(ag.actions);
        gpa.free(self.action_groups);
    }

    /// Emit deterministic, native Zig source code for this generated language
    pub fn emitZigSource(self: *const GeneratedData, gpa: std.mem.Allocator) ![]u8 {
        var buf = std.ArrayList(u8).empty;
        errdefer buf.deinit(gpa);

        const header = try std.fmt.allocPrint(gpa,
            \\// Generated by tree-sitter.zig native generator
            \\// Language: {s}
            \\// ABI Version: {d}
            \\
            \\const std = @import("std");
            \\const treesitter = @import("treesitter");
            \\const abi = treesitter.abi;
            \\
            \\pub const ABI_VERSION: u32 = {d};
            \\pub const STATE_COUNT: u32 = {d};
            \\pub const LARGE_STATE_COUNT: u32 = {d};
            \\pub const SYMBOL_COUNT: u32 = {d};
            \\pub const TOKEN_COUNT: u32 = {d};
            \\pub const EXTERNAL_TOKEN_COUNT: u32 = {d};
            \\pub const FIELD_COUNT: u32 = {d};
            \\
        , .{
            self.language_name,
            self.abi_version,
            self.abi_version,
            self.state_count,
            self.large_state_count,
            self.symbol_count,
            self.token_count,
            self.external_token_count,
            self.field_count,
        });
        defer gpa.free(header);
        try buf.appendSlice(gpa, header);

        // Symbol names
        try buf.appendSlice(gpa, "\npub const symbol_names = [_][:0]const u8{\n");
        for (self.symbol_names) |name| {
            try buf.appendSlice(gpa, "    \"");
            for (name) |c| {
                switch (c) {
                    '\\' => try buf.appendSlice(gpa, "\\\\"),
                    '"' => try buf.appendSlice(gpa, "\\\""),
                    '\n' => try buf.appendSlice(gpa, "\\n"),
                    '\r' => try buf.appendSlice(gpa, "\\r"),
                    '\t' => try buf.appendSlice(gpa, "\\t"),
                    0 => try buf.appendSlice(gpa, "\\x00"),
                    else => try buf.append(gpa, c),
                }
            }
            try buf.appendSlice(gpa, "\",\n");
        }
        try buf.appendSlice(gpa, "};\n");

        // Small parse table
        try buf.appendSlice(gpa, "\npub const small_parse_table = [_]u16{\n");
        for (self.small_parse_table, 0..) |v, i| {
            const num = try std.fmt.allocPrint(gpa, "{d},", .{v});
            defer gpa.free(num);
            try buf.appendSlice(gpa, num);
            if (i % 16 == 15) try buf.appendSlice(gpa, "\n");
        }
        try buf.appendSlice(gpa, "\n};\n");

        // Small parse table map
        try buf.appendSlice(gpa, "\npub const small_parse_table_map = [_]u32{\n");
        for (self.small_parse_table_map) |v| {
            const num = try std.fmt.allocPrint(gpa, "    {d},\n", .{v});
            defer gpa.free(num);
            try buf.appendSlice(gpa, num);
        }
        try buf.appendSlice(gpa, "};\n");

        // Footer / language constructor
        const footer = try std.fmt.allocPrint(gpa,
            \\
            \\pub fn language() abi.TSLanguage {{
            \\    return .{{
            \\        .abi_version = ABI_VERSION,
            \\        .symbol_count = SYMBOL_COUNT,
            \\        .alias_count = {d},
            \\        .token_count = TOKEN_COUNT,
            \\        .external_token_count = EXTERNAL_TOKEN_COUNT,
            \\        .state_count = STATE_COUNT,
            \\        .large_state_count = LARGE_STATE_COUNT,
            \\        .production_id_count = {d},
            \\        .field_count = FIELD_COUNT,
            \\        .max_alias_sequence_length = {d},
            \\        .parse_table = null,
            \\        .small_parse_table = &small_parse_table,
            \\        .small_parse_table_map = &small_parse_table_map,
            \\        .parse_actions = null,
            \\        .symbol_names = @ptrCast(&symbol_names),
            \\        .field_names = null,
            \\        .field_map_slices = null,
            \\        .field_map_entries = null,
            \\        .symbol_metadata = null,
            \\        .public_symbol_map = null,
            \\        .alias_map = null,
            \\        .alias_sequences = null,
            \\        .lex_modes = null,
            \\        .lex_fn = null,
            \\        .keyword_lex_fn = null,
            \\        .keyword_capture_token = 0,
            \\        .external_scanner = .{{}},
            \\        .primary_state_ids = null,
            \\        .name = "{s}",
            \\        .reserved_words = null,
            \\        .max_reserved_word_set_size = 0,
            \\        .supertype_count = 0,
            \\        .supertype_symbols = null,
            \\        .supertype_map_slices = null,
            \\        .supertype_map_entries = null,
            \\        .metadata = .{{}},
            \\    }};
            \\}}
            \\
        , .{
            self.alias_count,
            self.production_id_count,
            self.max_alias_sequence_length,
            self.language_name,
        });
        defer gpa.free(footer);
        try buf.appendSlice(gpa, footer);

        return try buf.toOwnedSlice(gpa);
    }
};

pub const Generator = struct {
    allocator: std.mem.Allocator,
    grammar: *const Grammar,

    symbols: std.ArrayList(SymbolInfo),
    productions: std.ArrayList(Production),
    token_count: u16 = 0,

    pub fn init(allocator: std.mem.Allocator, grammar: *const Grammar) Generator {
        return .{
            .allocator = allocator,
            .grammar = grammar,
            .symbols = std.ArrayList(SymbolInfo).empty,
            .productions = std.ArrayList(Production).empty,
        };
    }

    pub fn deinit(self: *Generator) void {
        const gpa = self.allocator;
        for (self.symbols.items) |s| gpa.free(s.name);
        self.symbols.deinit(gpa);
        for (self.productions.items) |p| gpa.free(p.rhs);
        self.productions.deinit(gpa);
    }

    pub fn generate(self: *Generator) !GeneratedData {
        const gpa = self.allocator;

        // 1. Symbol Collection
        try self.collectSymbols();

        // 2. Production Expansion
        try self.buildProductions();

        // 3. Build generated data structure
        var data = GeneratedData.init(gpa);
        errdefer data.deinit();

        data.language_name = try gpa.dupe(u8, self.grammar.name);
        data.abi_version = 14;
        data.symbol_count = @as(u32, @intCast(self.symbols.items.len));
        data.token_count = @as(u32, @intCast(self.token_count));
        data.external_token_count = @as(u32, @intCast(self.grammar.externals.items.len));
        data.large_state_count = 0; // Pure small parse tables

        // Symbol names and metadata
        var sym_names = try gpa.alloc([]const u8, self.symbols.items.len);
        var sym_meta = try gpa.alloc(abi.TSSymbolMetadata, self.symbols.items.len);
        var sym_map = try gpa.alloc(u16, self.symbols.items.len);

        for (self.symbols.items, 0..) |s, i| {
            sym_names[i] = try gpa.dupe(u8, s.name);
            sym_meta[i] = .{
                .visible = s.visible,
                .named = s.named,
                .supertype = false,
            };
            sym_map[i] = @as(u16, @intCast(i));
        }

        data.symbol_names = sym_names;
        data.symbol_metadata = sym_meta;
        data.symbol_map = sym_map;

        // Construct LR parse tables
        try self.buildParseTables(&data);

        return data;
    }

    fn collectSymbols(self: *Generator) !void {
        const gpa = self.allocator;

        // Symbol 0 is always end
        try self.symbols.append(gpa, .{
            .id = 0,
            .name = try gpa.dupe(u8, "end"),
            .kind = .end,
            .named = false,
            .visible = false,
        });

        // Collect terminal tokens first
        for (self.grammar.rules.items) |v| {
            try self.collectTerminalsFromRule(v.rule);
        }
        for (self.grammar.extras.items) |r| {
            try self.collectTerminalsFromRule(r);
        }

        self.token_count = @as(u16, @intCast(self.symbols.items.len));

        // Collect non-terminals from grammar rules
        for (self.grammar.rules.items) |v| {
            if (self.findSymbol(v.name) == null) {
                const id = @as(u16, @intCast(self.symbols.items.len));
                try self.symbols.append(gpa, .{
                    .id = id,
                    .name = try gpa.dupe(u8, v.name),
                    .kind = .non_terminal,
                    .named = true,
                    .visible = !std.mem.startsWith(u8, v.name, "_"),
                });
            }
        }
    }

    fn collectTerminalsFromRule(self: *Generator, rule: Rule) !void {
        const gpa = self.allocator;
        switch (rule.tag) {
            .string, .pattern => {
                if (rule.value) |val| {
                    if (self.findSymbol(val) == null) {
                        const id = @as(u16, @intCast(self.symbols.items.len));
                        try self.symbols.append(gpa, .{
                            .id = id,
                            .name = try gpa.dupe(u8, val),
                            .kind = .terminal,
                            .named = false,
                            .visible = true,
                        });
                    }
                }
            },
            .choice, .seq => {
                for (rule.children) |c| {
                    try self.collectTerminalsFromRule(c);
                }
            },
            .repeat, .repeat1, .optional, .field, .alias, .prec, .prec_left, .prec_right, .token => {
                for (rule.children) |c| {
                    try self.collectTerminalsFromRule(c);
                }
            },
            else => {},
        }
    }

    fn findSymbol(self: *const Generator, name: []const u8) ?u16 {
        for (self.symbols.items, 0..) |s, i| {
            if (std.mem.eql(u8, s.name, name)) return @as(u16, @intCast(i));
        }
        return null;
    }

    fn buildProductions(self: *Generator) !void {
        for (self.grammar.rules.items) |v| {
            const lhs = self.findSymbol(v.name) orelse continue;
            try self.flattenRule(lhs, v.rule);
        }
    }

    fn flattenRule(self: *Generator, lhs: u16, rule: Rule) !void {
        const gpa = self.allocator;
        switch (rule.tag) {
            .choice => {
                for (rule.children) |c| {
                    try self.flattenRule(lhs, c);
                }
            },
            .seq => {
                var rhs = std.ArrayList(u16).empty;
                errdefer rhs.deinit(gpa);
                for (rule.children) |c| {
                    if (c.tag == .symbol or c.tag == .string or c.tag == .pattern) {
                        if (c.value) |v| {
                            if (self.findSymbol(v)) |sym_id| {
                                try rhs.append(gpa, sym_id);
                            }
                        }
                    }
                }
                try self.productions.append(gpa, .{
                    .lhs = lhs,
                    .rhs = try rhs.toOwnedSlice(gpa),
                });
            },
            .symbol, .string, .pattern => {
                if (rule.value) |v| {
                    if (self.findSymbol(v)) |sym_id| {
                        var rhs = try gpa.alloc(u16, 1);
                        rhs[0] = sym_id;
                        try self.productions.append(gpa, .{
                            .lhs = lhs,
                            .rhs = rhs,
                        });
                    }
                }
            },
            .field, .alias, .prec, .prec_left, .prec_right, .token => {
                for (rule.children) |c| {
                    try self.flattenRule(lhs, c);
                }
            },
            else => {},
        }
    }

    fn buildParseTables(self: *Generator, data: *GeneratedData) !void {
        const gpa = self.allocator;

        // State 0: Initial state
        // State 1: Accepted / final state
        const state_count: u32 = @as(u32, @intCast(self.productions.items.len + 2));
        data.state_count = state_count;

        var small_table = std.ArrayList(u16).empty;
        defer small_table.deinit(gpa);
        var small_map = try gpa.alloc(u32, state_count);

        var action_groups = std.ArrayList(ActionGroup).empty;
        defer action_groups.deinit(gpa);

        // Action 0: None / empty
        const act0 = try gpa.alloc(GeneratedAction, 0);
        try action_groups.append(gpa, .{
            .index = 0,
            .count = 0,
            .reusable = false,
            .actions = act0,
        });

        // Action 1: Accept
        var act_accept = try gpa.alloc(GeneratedAction, 1);
        act_accept[0] = .{ .kind = .accept };
        try action_groups.append(gpa, .{
            .index = 1,
            .count = 1,
            .reusable = true,
            .actions = act_accept,
        });

        // Build states
        for (0..state_count) |s| {
            small_map[s] = @as(u32, @intCast(small_table.items.len));

            if (s == 0) {
                // Initial state: on start symbol, goto 1
                try small_table.append(gpa, 1); // 1 group
                try small_table.append(gpa, 1); // state 1
                try small_table.append(gpa, 1); // 1 symbol
                const start_sym = if (self.symbols.items.len > self.token_count) self.token_count else 0;
                try small_table.append(gpa, start_sym);
            } else if (s == 1) {
                // Accept state: on end (0), action 1 (accept)
                try small_table.append(gpa, 1); // 1 group
                try small_table.append(gpa, 1); // action 1
                try small_table.append(gpa, 1); // 1 symbol
                try small_table.append(gpa, 0); // end symbol
            } else {
                // Reduce state
                try small_table.append(gpa, 0); // 0 groups for leaf
            }
        }

        data.small_parse_table = try small_table.toOwnedSlice(gpa);
        data.small_parse_table_map = small_map;
        data.action_groups = try action_groups.toOwnedSlice(gpa);

        // Lex modes
        const lex_modes = try gpa.alloc(abi.TSLexerMode, state_count);
        @memset(lex_modes, .{});
        data.lex_modes = lex_modes;

        // Primary states
        var primary_states = try gpa.alloc(u16, state_count);
        for (0..state_count) |i| primary_states[i] = @as(u16, @intCast(i));
        data.primary_state_ids = primary_states;
    }
};

test "generator: generate parser data and emit zig source from grammar" {
    var g = try Grammar.init(std.testing.allocator, "simple");
    defer g.deinit(std.testing.allocator);

    try g.addRule(std.testing.allocator, "expression", Rule.str("+"));

    var gen = Generator.init(std.testing.allocator, &g);
    defer gen.deinit();

    var data = try gen.generate();
    defer data.deinit();

    try std.testing.expectEqualStrings("simple", data.language_name);
    try std.testing.expect(data.symbol_count >= 2);
    try std.testing.expect(data.state_count >= 2);
    try std.testing.expect(data.small_parse_table.len > 0);

    const zig_source = try data.emitZigSource(std.testing.allocator);
    defer std.testing.allocator.free(zig_source);

    try std.testing.expect(zig_source.len > 0);
    try std.testing.expect(std.mem.indexOf(u8, zig_source, "pub fn language()") != null);
}
